import { readFile, mkdir, writeFile } from 'node:fs/promises'
import { stripTypeScriptTypes } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { presetDefinitions } from '../src/presets.ts'

const root = fileURLToPath(new URL('../', import.meta.url))
const checking = process.argv.includes('--check')
const stale = []
const sources = {
  product: { 'presets': 'src/presets.ts' },
  collaboration: { 'tools': 'src/tools.ts' },
  sandbox: {
    'tools': 'src/tools.ts',
    'policy': 'packages/sandbox/src/policy.ts',
    'reviewer': 'packages/sandbox/src/reviewer.ts',
  },
}
const notice = '// Generated by scripts/build.mjs. Edit the TypeScript source.\n'
const runtimeMarker = '// Runtime source\n'

async function emit(relative, content) {
  const path = join(root, relative)
  if (checking) {
    if (await readFile(path, 'utf8').catch(() => '') !== content) stale.push(relative)
  } else {
    await mkdir(dirname(path), { recursive: true })
    await writeFile(path, content, 'utf8')
  }
}

async function compile(source) {
  const text = await readFile(join(root, source), 'utf8')
  const marker = text.indexOf(runtimeMarker)
  const body = marker === -1 ? text : text.slice(marker + runtimeMarker.length)
  return notice + stripTypeScriptTypes(body)
    .replaceAll('../../../src/', './')
    .replace(/\bctx {2,}(?=[,)])/g, 'ctx')
    .replace(/\bconfig {2,}=/g, 'config =')
}

const client = await compile('packages/collaboration/src/client.ts')
for (const [layer, modules] of Object.entries(sources)) {
  const output = [
    ['index.js', await compile('packages/' + layer + '/src/index.ts')],
    ...await Promise.all(Object.entries(modules).map(async ([name, file]) => [name + '.js', await compile(file)])),
  ]
  for (const base of ['lib/' + layer, 'packages/' + layer + '/lib/' + layer]) {
    for (const [file, content] of output) await emit(base + '/' + file, content)
    if (layer === 'collaboration') {
      const id = base.startsWith('lib/') ? 'dsh-codex-modes' : 'dsh-codex-collaboration'
      await emit(base + '/client.js', client.replace('__PACKAGE_ID__', id))
    }
    if (layer === 'product') {
      for (const { id, name, description, order, plugins } of presetDefinitions(false)) {
        const target = base + '/presets/' + id
        await emit(target + '/preset.yml', JSON.stringify({ name, description, order }, null, 2) + '\n')
        const entries = plugins.filter(plugin => plugin.id !== 'tool-bash')
        const yaml = entries.map(row => '- id: ' + row.id + '\n  name: ' + JSON.stringify(row.name)).join('\n')
        await emit(target + '/agent.cordis.yml', yaml +
          '\n- id: tool-bash\n  name: "@deepseek-ai/dsh-tool-bash"\n  disabled: !!js process.platform === "win32"\n' +
          '- id: tool-pwsh\n  name: "@deepseek-ai/dsh-tool-pwsh"\n  disabled: !!js process.platform !== "win32"\n')
      }
    }
  }
}
if (stale.length) {
  console.error('Rebuild generated files with npm run build:\n' + stale.join('\n'))
  process.exitCode = 1
}
